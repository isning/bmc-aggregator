"""Generate feature DTOs from the endpoint contract; --check is used by CI."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def field_type(spec):
    if "enum" in spec:
        return " | ".join(json.dumps(value) for value in spec["enum"])
    if "properties" in spec:
        return "{ " + "; ".join(f"{name}: {field_type(value)}" for name, value in spec["properties"].items()) + " }"
    return " | ".join(spec["type"])


def render():
    schemas = json.loads((ROOT / "contracts/feature-config.schema.json").read_text())["$defs"]
    lines = ["// Generated by scripts/generate_feature_contracts.py. Do not edit.", ""]
    for name, schema in schemas.items():
        lines.append(f"export interface {name} {{")
        for field, spec in schema["properties"].items():
            optional = "" if field in schema["required"] else "?"
            lines.append(f"  {field}{optional}: {field_type(spec)}")
        lines.extend(["}", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    destination = ROOT / "frontend/src/types/featureConfig.ts"
    expected = render()
    if args.check:
        if destination.read_text() != expected:
            parser.exit(1, "Feature DTOs are stale; run python3 scripts/generate_feature_contracts.py\n")
    else:
        destination.write_text(expected)


if __name__ == "__main__":
    main()
